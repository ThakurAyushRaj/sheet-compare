import fs from 'node:fs';
import assert from 'node:assert/strict';
import ts from 'typescript';
import * as XLSX from 'xlsx';
const source=fs.readFileSync(new URL('./src/main.tsx',import.meta.url),'utf8');
const body=source.slice(source.indexOf('export function compare'),source.indexOf('function App()')).replace('export function','function');
const compare=new Function(ts.transpile(body,{target:ts.ScriptTarget.ES2022})+';return compare;')();
const book=data=>{const b=XLSX.utils.book_new();XLSX.utils.book_append_sheet(b,XLSX.utils.aoa_to_sheet(data),'Data');return b;};
const a=book([['Item','Count'],['Book',10],['Pen',5]]);
const b=book([['Item','Count'],['Book',12],['Pen'],['New',3]]);
assert.equal(compare(a,a).diffs.length,0);
const result=compare(a,b);
assert.deepEqual(result.diffs.map(d=>[d.cell,d.type]),[['B2','Changed'],['B3','Removed'],['A4','Added'],['B4','Added']]);
assert.equal(compare(book([[' hello ']]),book([['hello']])).diffs.length,0);
assert.equal(compare(book([['hello']]),book([['HELLO']]),true,true).diffs.length,0);
assert.equal(compare(book([['hello']]),book([['HELLO']]),true,false).diffs.length,1);
assert.equal(compare(book([[0,false]]),book([['','']])).diffs.length,2);
const extra=book([['a']]); XLSX.utils.book_append_sheet(extra,XLSX.utils.aoa_to_sheet([['extra']]),'New sheet');
assert.equal(compare(book([['a']]),extra).diffs[0].sheet,'New sheet');
console.log('Passed: identical files, changed/added/removed cells, whitespace, case, zero/false, and added sheets.');
