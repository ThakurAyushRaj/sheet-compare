import fs from 'node:fs';
import assert from 'node:assert/strict';
import ts from 'typescript';
import * as XLSX from 'xlsx';
const source=fs.readFileSync(new URL('./src/main.tsx',import.meta.url),'utf8');
const body=source.slice(source.indexOf('export function compare'),source.indexOf('function App()')).replace('export function','function');
const compare=new Function('XLSX',ts.transpile(body,{target:ts.ScriptTarget.ES2022})+';return compare;')(XLSX);
const book=(data,name='Data')=>{const b=XLSX.utils.book_new();XLSX.utils.book_append_sheet(b,XLSX.utils.aoa_to_sheet(data),name);return b;};
const roundtrip=b=>XLSX.read(XLSX.write(b,{type:'buffer',bookType:'xlsx'}),{type:'array'});
const headers=['unit_no','status','unit_description','plot_size','width','length','dimension_unit','unit_id','project_id','block_name','location','grid_row','grid_column','price','created_at','updated_at'];
const original=['A1','Available','Corner',229.44,10,22.944,'m',1,1,'A','North',1,1,100,'Yesterday','Yesterday'];
const updated=['A1','Sold','Garden',229.5,11,23,'ft',2,2,'B','South',2,2,200,'Today','Today'];
const a=roundtrip(book([headers,original]));
const b=roundtrip(book([headers,updated],'Different sheet'));
assert.equal(compare(a,a).diffs.length,0);
const result=compare(a,b);
assert.deepEqual(result.diffs.map(d=>d.field),['Status','Unit Description','Plot Size','Width','Length','Dimension Unit']);
assert.equal(result.diffs.find(d=>d.field==='Plot Size').value,'229.5');
assert.equal(compare(a,book([headers,[...original.slice(0,7),...updated.slice(7)]])).diffs.length,0);
assert.equal(compare(book([['Unit No.','Status'],[1,'Available']]),book([['unit_no','status'],[1,'available']]),true,true).diffs.length,0);
assert.equal(compare(book([['Unit No.','Width'],[1,0]]),book([['unit_no','width'],[1,1]])).diffs.length,1);
assert.equal(compare(book([['Unit No.','Width'],[1,10]]),book([['unit_no','width'],[1,'']])).diffs.length,0);
assert.equal(compare(book([['Unit No.','Width'],[1,10]]),book([['unit_no','width'],[1,10],[2,20]])).diffs.length,0);
assert.equal(compare(book([['Unit No.','Plot Size'],['A1',229.44]]),book([['plot_size','unit_no'],[229.5,'A1']])).diffs[0].field,'Plot Size');
const csv=XLSX.read('unit_no,plot_size\nA1,229.5',{type:'string'});
assert.equal(compare(book([['Unit No.','Plot Size'],['A1',229.44]]),csv).diffs[0].value,'229.5');
assert.throws(()=>compare(book([['price'],[1]]),book([['price'],[2]])),/Unit No. column/);
console.log('Passed: seven allowed fields, excluded metadata, decimal changes, different sheet names, reordered columns, CSV, blank/added cells, case, and zero.');

const ordered=book([['Unit No.','Plot Size','Status'],[1,229.44,'Available'],[2,100,'Sold'],[3,50,'Available']]);
const reordered=book([['status','plot_size','unit_no'],['Available',50,3],['Available',229.5,1],['Sold',100,2]]);
const changes=compare(ordered,reordered).diffs;
assert.equal(changes.length,1);
assert.equal(changes[0].unit,'1');
assert.equal(changes[0].old,'229.44');
assert.equal(changes[0].value,'229.5');
assert.equal(changes[0].cell,'B2');
assert.equal(changes[0].rightCell,'B3');
assert.equal(compare(ordered,book([['Unit No.','Plot Size','Status'],[3,50,'Available'],[1,229.44,'Available'],[2,100,'Sold']])).diffs.length,0);
assert.throws(()=>compare(ordered,book([['Unit No.','Plot Size'],[1,10],[1,20]])),/Duplicate Unit No/);
assert.throws(()=>compare(ordered,book([['Unit No.','Plot Size'],[99,10]])),/No matching unit numbers/);
console.log('Passed: rows matched by Unit No.; reordered rows and columns; correct cell locations; duplicate and unmatched unit validation.');
